  var HTML_KEYS = { heroTitle: true };
  var current = 'uz';
  try {
    var saved = localStorage.getItem('kali_lang');
    if (saved && DICT[saved]) current = saved;
  } catch (e) {}
  /* ?lang=uz|ru|en — SEO hreflang havolalari uchun */
  try {
    var m = /[?&]lang=(uz|ru|en)(?:[&#]|$)/.exec(window.location.search || '');
    if (m && DICT[m[1]]) current = m[1];
  } catch (e) {}

  function t(key, vars) {
    var value = (DICT[current] && DICT[current][key]) || (DICT.uz[key]) || key;
    if (vars) Object.keys(vars).forEach(function (k) { value = value.split('{' + k + '}').join(vars[k]); });
    return value;
  }

  function apply(root) {
    var scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach(function (el) {
      var key = el.getAttribute('data-i18n');
      if (HTML_KEYS[key]) el.innerHTML = t(key);
      else el.textContent = t(key);
    });
    scope.querySelectorAll('[data-i18n-ph]').forEach(function (el) {
      el.setAttribute('placeholder', t(el.getAttribute('data-i18n-ph')));
    });
    scope.querySelectorAll('[data-i18n-aria]').forEach(function (el) {
      el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')));
    });
    scope.querySelectorAll('[data-i18n-title]').forEach(function (el) {
      el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
      if (el.hasAttribute('aria-label')) el.setAttribute('aria-label', t(el.getAttribute('data-i18n-title')));
    });
    document.documentElement.lang = current;
    document.dispatchEvent(new CustomEvent('langchange', { detail: { lang: current } }));
  }

  function setLang(lang) {
    if (!DICT[lang]) return;
    current = lang;
    try { localStorage.setItem('kali_lang', lang); } catch (e) {}
    apply();
  }

  window.I18N = {
    t: t, apply: apply, setLang: setLang,
    getLang: function () { return current; }, dict: DICT
  };
